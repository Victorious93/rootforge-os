// Release signing comes only from the environment (CI secrets or a local
// export). Nothing about it is committed; without it no release APK is built.
val releaseKeystore: String? = System.getenv("ROOTFORGE_KEYSTORE_FILE")?.takeIf { it.isNotBlank() }

android {
    namespace = "ai.rootforge.os"
    compileSdk = 35

    defaultConfig {
        applicationId = "ai.rootforge.os"
        minSdk = 26
        targetSdk = 35
        versionCode = 1
        versionName = "0.1.0"
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    signingConfigs {
        // Debug-only key committed at app/debug.keystore so every local and CI
        // debug build has the same signing certificate. Not a secret; never
        // use it for release.
        getByName("debug") {
            storeFile = file("debug.keystore")
            storePassword = "android"
            keyAlias = "androiddebugkey"
            keyPassword = "android"
        }
        if (releaseKeystore != null) {
            create("release") {
                storeFile = file(releaseKeystore)
                storePassword = System.getenv("ROOTFORGE_KEYSTORE_PASSWORD")
                keyAlias = System.getenv("ROOTFORGE_KEY_ALIAS")
                keyPassword = System.getenv("ROOTFORGE_KEY_PASSWORD")
            }
        }
    }

    buildTypes {
        debug {
            applicationIdSuffix = ".debug"
            signingConfig = signingConfigs.getByName("debug")
            versionNameSuffix = "-debug"
        }
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            if (releaseKeystore != null) {
                signingConfig = signingConfigs.getByName("release")
            }
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlinOptions {
        jvmTarget = "17"
    }
    buildFeatures {
        compose = true
